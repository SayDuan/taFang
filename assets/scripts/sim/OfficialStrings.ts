export function officialString(key: string, fallback = ''): string {
    return OFFICIAL_STRINGS[key] ?? fallback;
}

/** 官方关卡预览字符串后缀。不要把战役第 11 关写成 T_LEVEL_NAME_11。 */
export function levelOverviewKey(level: number): string {
    if (level < 1 || level > 60) {
        return '';
    }
    if (level <= 9) {
        return `0${level}`;
    }
    if (level === 10) {
        return '10';
    }
    return String(level + 3);
}

export function officialLevelName(level: number): string {
    const key = levelOverviewKey(level);
    return key ? officialString(`T_LEVEL_NAME_${key}`, `第 ${level} 关`) : `第 ${level} 关`;
}

export function officialLevelInfo(level: number): string {
    const key = levelOverviewKey(level);
    return key ? officialString(`T_LEVEL_INFO_${key}`) : '';
}

